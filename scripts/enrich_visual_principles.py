def main() -> None:
    payload = json.loads(PATH.read_text(encoding="utf-8"))
    explainers = payload["explainers"]
    actual = {item["lesson_id"] for item in explainers}
    if actual != set(GUIDES):
        raise SystemExit(f"图解ID与读图指南不一致：缺{set(GUIDES)-actual}，多{actual-set(GUIDES)}")
    for item in explainers:
        obj, change, result, conclusion = GUIDES[item["lesson_id"]]
        item["reading_guide"] = {
            "object": obj,
            "change": change,
            "result": result,
            "conclusion": conclusion,
        }
    payload["version"] = 2
    payload["design_note"] = "原创轻漫画式科普：先用生活比喻建立直觉，再用看谁—比什么—看到什么—得结论的读图链回到可检验模型；比喻不代替定义。"
    PATH.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
